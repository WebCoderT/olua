#!/usr/bin/env node
/**
 * 生成物一致性审计（api generated audit）
 *
 * 「客户端和服务端的接口文件必须通过 swagger 生成」这条约定，光靠人自觉守不住 ——
 * 有人手改一次生成物，下一次重新生成就悄悄回滚；有人加了接口忘了重新生成，两端就停在旧契约上。
 * 本脚本把这条约定变成可执行的检查。
 *
 * 链路的唯一方向（README / FAQ 里同一张图）：
 *
 *   server/src（控制器 + DTO + 装饰器）
 *        │  cd server && npm run swagger:emit
 *        ▼
 *   server/openapi.json（机器可读契约，提交进仓库）
 *        │  node tools/gen-api.cjs
 *        ▼
 *   客户端 assets/ui/utils/net/{ApiRoutes,ApiModels,Api}.ts + 管理端 admin/src/api/{routes,models,endpoints}.ts
 *
 * 七段检查：
 *   A 生成物与文档一致 —— 用生成器现算一遍，逐字节比对磁盘产物（落后 / 缺失即 FAIL）
 *   B 生成物带头标记   —— 每个生成文件第一行区必须是 `@generated by tools/gen-api.cjs`
 *   C 接口全覆盖       —— 文档里每个 operationId 都要落到端点文件的方法上，且不带「多端重复」
 *   D 类型不悬空       —— 端点文件 import 的类型都要在 types 文件里有对应导出
 *   E 路径只在路径表 —— 端点文件与业务代码里不许出现路径字符串（唯一来源是 routes 文件）
 *   F Cocos meta      —— 客户端生成物必须有 .meta（否则引擎不认这个脚本）
 *   G 契约完整度       —— 每个接口都要有 operationId / 分组 / 受众；响应要有 data 类型扩展
 *
 * 用法：
 *   node tools/audit-api-generated.cjs          # 报告（有问题退出码 1）
 *   node tools/audit-api-generated.cjs --json   # 输出 JSON
 */

"use strict";

const fs = require("node:fs");
const path = require("node:path");

const ROOT = path.resolve(__dirname, "..");
const args = process.argv.slice(2);
const AS_JSON = args.includes("--json");

const { buildOutputs, readDoc, GENERATED_MARK, TARGETS, OPENAPI_FILE } = require("./gen-api.cjs");

const relOf = (full) => path.relative(ROOT, full).split(path.sep).join("/");

const problems = [];
const fail = (section, detail) => problems.push({ section, detail });
const relDoc = relOf(OPENAPI_FILE);

//#region A 生成物与文档一致

const { operations, outputs } = buildOutputs();
const stale = [];
for (const [file, content] of outputs) {
  const rel = relOf(file);
  const current = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null;
  if (current === null) stale.push({ file: rel, status: "缺失" });
  else if (current !== content) stale.push({ file: rel, status: "与文档不一致" });
}
for (const item of stale) fail("A 生成物与文档一致", `${item.file}（${item.status}）—— 执行 \`cd server && npm run gen:api\``);

//#endregion

//#region B 生成物带头标记

const generatedFiles = new Map(); // rel → 内容
for (const [file, content] of outputs) generatedFiles.set(relOf(file), { full: file, content });

for (const [rel, item] of generatedFiles) {
  if (!item.content.includes(GENERATED_MARK)) {
    fail("B 生成物带头标记", `${rel} 缺少 \`${GENERATED_MARK}\` 头`);
  }
  // 头标记必须在文件最开头的注释块里（不能是文件中间的普通注释）
  const head = item.content.slice(0, 400);
  if (!head.includes(GENERATED_MARK)) fail("B 生成物带头标记", `${rel} 的标记不在文件开头`);
}

//#endregion

//#region C 接口全覆盖

/** 端点文件里出现的方法名（`  async 方法名(` 或 `方法名: (` 之类）——统一按「名字 + 冒号或括号」找 */
function occurrences(text, token) {
  return new RegExp(`(^|[^\\w$])${token.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}([^\\w$]|$)`, "gm").test(text);
}

const readOf = (target, name) => {
  const file = path.join(target.dir, name);
  return fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "";
};

const endpointsOf = new Map(); // target.key → 内容
const routesOf = new Map(); // target.key → 内容
for (const target of Object.values(TARGETS)) {
  endpointsOf.set(target.key, readOf(target, target.endpointsFile));
  routesOf.set(target.key, readOf(target, target.routesFile));
}

/** 路径字面量 → 能同时匹配「字符串形式」与「模板字符串形式」的正则 */
function pathPattern(op) {
  const escaped = op.path.replace(/[.*+?^${}()|[\]\\]/g, "\\$&").replace(/\\\{[^}]+\\\}/g, "\\$\\{[^}]*\\}");
  // 两端用引号/反引号夹住，避免 `/roles` 误配 `/roles/online`
  return new RegExp(`["'\`]${escaped}["'\`]`);
}

const opsByTarget = new Map(); // target.key → operations[]
for (const op of operations) {
  if (!opsByTarget.has(op.target)) opsByTarget.set(op.target, []);
  opsByTarget.get(op.target).push(op);

  const text = endpointsOf.get(op.target) ?? "";
  if (!occurrences(text, op.methodName)) {
    fail("C 接口全覆盖", `${TARGETS[op.target].label}端点文件里找不到方法 ${op.methodName}（来自 ${op.source}）`);
  }

  // 路径必须登记在**自己这一端**的路径表里
  const pattern = pathPattern(op);
  if (!pattern.test(routesOf.get(op.target) ?? "")) {
    fail("C 接口全覆盖", `${op.source} 的路径没登记在 ${relOf(path.join(TARGETS[op.target].dir, TARGETS[op.target].routesFile))}`);
  }
  // 且不能出现在另一端的路径表里（归错端 = 调用方拿不到令牌受众）
  for (const [key, other] of routesOf) {
    if (key === op.target) continue;
    if (pattern.test(other)) fail("C 接口全覆盖", `${op.source} 的路径出现在${TARGETS[key].label}路径表里（应只归${TARGETS[op.target].label}）`);
  }
}

// 反向：端点文件里的方法必须都能在文档里找到（防手写野生方法）
for (const target of Object.values(TARGETS)) {
  const text = endpointsOf.get(target.key) ?? "";
  const declared = [...text.matchAll(/^\s{2}([A-Za-z_$][\w$]*)\s*[:(]/gm)].map((m) => m[1]);
  const known = new Set((opsByTarget.get(target.key) ?? []).map((op) => op.methodName));
  for (const name of declared) {
    if (!known.has(name)) fail("C 接口全覆盖", `${target.label}端点文件里的 ${name} 不在文档里（手写？）`);
  }
}

// 同一个模块内方法名不能重复（跨模块重名是正常的，例如三个模块都有 list）
const byExport = new Map();
for (const op of operations) {
  if (!byExport.has(op.export)) byExport.set(op.export, new Set());
  const seen = byExport.get(op.export);
  if (seen.has(op.methodName)) fail("C 接口全覆盖", `${op.export} 里出现重复方法名 ${op.methodName}`);
  seen.add(op.methodName);
}

//#endregion

//#region D 类型不悬空

for (const target of Object.values(TARGETS)) {
  const endpoints = endpointsOf.get(target.key) ?? "";
  const modelsFile = path.join(target.dir, target.modelsFile);
  const models = fs.existsSync(modelsFile) ? fs.readFileSync(modelsFile, "utf8") : "";
  const exported = new Set([...models.matchAll(/^export (?:type|const|interface) ([A-Za-z_$][\w$]*)/gm)].map((m) => m[1]));

  const imported = [...endpoints.matchAll(/import type \{([^}]*)\} from "\.\/(?:ApiModels|models)"/g)]
    .flatMap((m) => m[1].split(","))
    .map((part) => part.trim())
    .filter(Boolean);
  for (const name of imported) {
    if (!exported.has(name)) fail("D 类型不悬空", `${target.label}端点文件 import 了 ${name}，但 ${target.modelsFile} 里没有导出它`);
  }
}

//#endregion

//#region E 路径只在路径表

for (const target of Object.values(TARGETS)) {
  const endpoints = endpointsOf.get(target.key) ?? "";
  const routesFile = relOf(path.join(target.dir, target.routesFile));
  // 端点文件里出现「/xxx」形式的字符串（排除 JSDoc 注释与 import 路径）
  endpoints.split(/\r?\n/).forEach((line, index) => {
    const trimmed = line.trim();
    if (trimmed.startsWith("*") || trimmed.startsWith("//") || trimmed.startsWith("/*")) return;
    if (/from\s+["']\.\//.test(line)) return;
    if (/["'`]\/[a-z]/.test(line)) fail("E 路径只在路径表", `${target.label}端点文件第 ${index + 1} 行出现路径字面量，应引用 ${routesFile}`);
  });
}

//#endregion

//#region F Cocos meta

for (const target of Object.values(TARGETS)) {
  if (!path.join(target.dir, "").startsWith(path.join(ROOT, "assets"))) continue;
  for (const name of [target.routesFile, target.modelsFile, target.endpointsFile]) {
    const file = path.join(target.dir, name);
    if (!fs.existsSync(`${file}.meta`)) fail("F Cocos meta", `${relOf(file)}.meta 缺失（Cocos 不认没有 meta 的脚本）`);
  }
}

//#endregion

//#region G 契约完整度

const doc = readDoc();
const auditOps = new Set();
for (const [rawPath, item] of Object.entries(doc.paths ?? {})) {
  for (const method of ["get", "post", "put", "patch", "delete"]) {
    const op = item[method];
    if (!op) continue;
    const where = `${method.toUpperCase()} ${rawPath}`;
    if (auditOps.has(where)) continue;
    auditOps.add(where);
    if (!op.operationId) fail("G 契约完整度", `${where} 缺 operationId（生成器要用它决定生成到哪个模块）`);
    if (!op.tags?.length) fail("G 契约完整度", `${where} 缺分组标签（@ApiXxxDoc 提供）`);
    if (!op["x-olua-audience"]) fail("G 契约完整度", `${where} 缺 x-olua-audience（生成器据此决定是否带令牌）`);
    if (!("responses" in op)) fail("G 契约完整度", `${where} 没有响应声明`);
  }
}

// 有返回数据的接口必须声明 data 类型（否则两端只能拿到 null）
for (const op of operations) {
  const ok = op.dataSchema !== null || op.audience === "public" || op.dataNullable;
  if (op.dataSchema === null && !ok) {
    fail("G 契约完整度", `${op.source} 没有声明 data 类型（应加 @ApiDataResponse）`);
  }
}

//#endregion

//#region 报告

const bySection = {};
for (const item of problems) bySection[item.section] = (bySection[item.section] || 0) + 1;

if (AS_JSON) {
  console.log(
    JSON.stringify(
      {
        operations: operations.length,
        outputs: outputs.size,
        byTarget: Object.fromEntries([...opsByTarget].map(([key, list]) => [key, list.length])),
        problems,
      },
      null,
      2,
    ),
  );
  process.exit(problems.length ? 1 : 0);
}

console.log("生成物一致性审计 / api generated audit");
console.log(`契约：${relDoc}（${operations.length} 个接口）`);
console.log(`生成物：${outputs.size} 个文件`);
for (const [key, list] of opsByTarget) {
  console.log(`  · ${TARGETS[key].label} ${String(list.length).padStart(2)} 个接口 → ${relOf(path.join(TARGETS[key].dir, TARGETS[key].endpointsFile))}`);
}
console.log("");

console.log("检查项：");
console.log(`  A 生成物与文档一致    ${stale.length ? `✗ ${stale.length} 个文件落后` : "✓"}`);
console.log(`  B 生成物带头标记      ${bySection["B 生成物带头标记"] ? `✗ ${bySection["B 生成物带头标记"]}` : "✓"}`);
console.log(`  C 接口全覆盖          ${bySection["C 接口全覆盖"] ? `✗ ${bySection["C 接口全覆盖"]}` : `✓ ${operations.length} 个接口都落地`}`);
console.log(`  D 类型不悬空          ${bySection["D 类型不悬空"] ? `✗ ${bySection["D 类型不悬空"]}` : "✓"}`);
console.log(`  E 路径只在路径表      ${bySection["E 路径只在路径表"] ? `✗ ${bySection["E 路径只在路径表"]}` : "✓"}`);
console.log(`  F Cocos meta          ${bySection["F Cocos meta"] ? `✗ ${bySection["F Cocos meta"]}` : "✓"}`);
console.log(`  G 契约完整度          ${bySection["G 契约完整度"] ? `✗ ${bySection["G 契约完整度"]}` : "✓"}`);
console.log("");

if (problems.length) {
  for (const section of Object.keys(bySection)) {
    console.log(`${section}：`);
    for (const item of problems.filter((p) => p.section === section)) console.log(`  ✗ ${item.detail}`);
  }
  console.log("");
  console.log(`FAIL：${problems.length} 处不符合「接口文件由 swagger 生成」的约定`);
  console.log("怎么改：改服务端的控制器 / DTO（含 operationId、@ApiDataResponse），然后 `cd server && npm run gen:api`");
  process.exit(1);
}

console.log(`PASS：${operations.length} 个接口全部由 ${relDoc} 生成，两端生成物与文档一致且未被手改`);
process.exit(0);

//#endregion
