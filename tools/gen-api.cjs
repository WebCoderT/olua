//#region 生成：接口方法

function argListOf(op) {
  const args = op.pathParams.map((name) => `${name}: string`);
  if (op.bodySchema) args.push(`body: ${op.bodyTypeName ?? "Record<string, unknown>"}`);
  if (op.queryTypeName) args.push(`query: ${op.queryTypeName} = {}`);
  args.push("options?: Options");
  return args;
}

/** 请求选项对象表达式 */
function optionsExpression(op) {
  const parts = [];
  if (op.queryTypeName) parts.push("query");
  if (op.audience === "public") parts.push("auth: false");
  parts.push("...options");
  return parts.length === 1 ? "options" : `{ ${parts.join(", ")} }`;
}

function callExpression(op, target) {
  const ret = returnTypeOf(op);
  const pathExpr = op.pathParams.length
    ? `${target.routesConst}.${op.moduleKey}.${op.methodName}(${op.pathParams.join(", ")})`
    : `${target.routesConst}.${op.moduleKey}.${op.methodName}`;
  const opts = optionsExpression(op);

  if (op.method === "GET" || op.method === "DELETE") {
    const fn = op.method === "GET" ? "get" : "del";
    return `${target.requestEntry}.${fn}<${ret}>(${pathExpr}, ${opts})`;
  }
  const fn = op.method === "POST" ? "post" : op.method === "PUT" ? "put" : "patch";
  return `${target.requestEntry}.${fn}<${ret}>(${pathExpr}, ${op.bodySchema ? "body" : "undefined"}, ${opts})`;
}

function emitEndpointsFile(target, operations, modelNames, allModelNames) {
  const groups = new Map();
  for (const op of operations) {
    if (!groups.has(op.export)) groups.set(op.export, []);
    groups.get(op.export).push(op);
  }

  const isClient = target.key === "client";
  const modelsModule = isClient ? "./ApiModels" : "./models";

  const lines = [];
  lines.push(...header(target, target.endpointsFile));
  lines.push("");
  if (isClient) {
    lines.push('import HttpClient from "./HttpClient";');
    lines.push('import type { RequestOptions } from "./HttpClient";');
  } else {
    lines.push('import { http } from "./http";');
    lines.push('import type { HttpOptions } from "./http";');
  }
  lines.push(`import { ${target.routesConst} } from "./${target.routesFile.replace(/\.ts$/, "")}";`);
  lines.push(`import type { ${modelNames.join(", ")} } from "${modelsModule}";`);
  lines.push("");
  lines.push(...emitDoc("", target.endpointsDoc));
  lines.push("");
  lines.push(...emitDoc("", ["请求选项：method / path / body 已由生成的方法填好，调用方只管 silent、timeout 之类的开关"]));
  lines.push(isClient ? 'type Options = Omit<RequestOptions, "method" | "path" | "body">;' : "type Options = HttpOptions;");
  lines.push("");
  lines.push("// 模型类型再导出一次：调用方 `import type { RoleSummary } from \"./Api\"` 这类既有写法仍然可用");
  lines.push(`export type { ${allModelNames.join(", ")} } from "${modelsModule}";`);
  lines.push("");

  for (const [exportName, group] of groups) {
    lines.push(`/** ${group[0].moduleKey} 模块的接口（${group.length} 个，生成） */`);
    lines.push(`export const ${exportName} = {`);
    for (const op of group) {
      const doc = [op.summary ? `${op.summary}（${op.source}）` : op.source];
      if (op.description && op.description !== op.summary) doc.push("", op.description);
      if (op.permissions.length) doc.push("", `权限点：${op.permissions.join("、")}`);
      lines.push(...emitDoc("  ", doc));
      lines.push(`  ${op.methodName}: (${argListOf(op).join(", ")}) => ${callExpression(op, target)},`);
    }
    lines.push("};");
    lines.push("");
  }
  return lines.join("\n");
}

