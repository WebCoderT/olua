//#region 收集接口

function collectOperations(doc) {
  const operations = [];
  const seen = new Map();

  for (const [rawPath, item] of Object.entries(doc.paths ?? {})) {
    for (const method of ["get", "post", "put", "patch", "delete"]) {
      const op = item[method];
      if (!op) continue;

      const operationId = op.operationId;
      if (!operationId) throw new Error(`${method.toUpperCase()} ${rawPath} 缺少 operationId（服务端要用 @ApiXxxDoc 声明）`);
      if (seen.has(operationId)) {
        throw new Error(`operationId 重复：${operationId}（${seen.get(operationId)} 与 ${method.toUpperCase()} ${rawPath}）`);
      }
      seen.set(operationId, `${method.toUpperCase()} ${rawPath}`);

      const dot = operationId.lastIndexOf(".");
      if (dot <= 0) throw new Error(`operationId 需形如「模块.方法」：${operationId}（${method.toUpperCase()} ${rawPath}）`);
      const moduleKey = operationId.slice(0, dot);
      const methodName = operationId.slice(dot + 1);

      const meta = MODULES[moduleKey];
      if (!meta) {
        throw new Error(`operationId 的模块段没登记：${moduleKey}（${operationId}）—— 请在 tools/gen-api.cjs 的 MODULES 里补一条`);
      }

      // 文档路径一般不带全局前缀（服务端 setGlobalPrefix 不会进文档）；带上时也能兼容
      const fullPath = rawPath.startsWith(API_PREFIX) ? rawPath.slice(API_PREFIX.length) : rawPath;
      if (!fullPath.startsWith("/")) throw new Error(`路径不合法：${rawPath}`);

      // 归哪一端只看路径：管理端接口全在 /admin 下（与 Swagger 分组的「管理端」一一对应）
      const expectedTarget = fullPath === "/admin" || fullPath.startsWith("/admin/") ? "admin" : "client";
      if (meta.target !== expectedTarget) {
        throw new Error(`${operationId} 的路径是 ${rawPath}，应归 ${expectedTarget}，但 MODULES 里登记的是 ${meta.target}`);
      }

      const parameters = op.parameters ?? [];
      const templateParams = [...fullPath.matchAll(/\{([^}]+)\}/g)].map((match) => match[1]);
      const declaredPathParams = parameters.filter((param) => param.in === "path").map((param) => param.name);
      for (const name of templateParams) {
        if (!declaredPathParams.includes(name)) throw new Error(`${rawPath} 的路径参数 {${name}} 没有对应的 parameters 声明`);
      }

      const queryParams = parameters
        .filter((param) => param.in === "query")
        .map((param) => ({ name: param.name, required: param.required === true, description: param.description, schema: param.schema ?? {} }));

      const bodySchema = op.requestBody?.content?.["application/json"]?.schema ?? null;
      const synthesizedQueryName = queryParams.length ? `${pascal(moduleKey)}${pascal(methodName)}Query` : null;

      operations.push({
        doc,
        moduleKey,
        methodName,
        export: meta.export,
        target: meta.target,
        method: method.toUpperCase(),
        /** 剥掉 /api 前缀的路径（两端 baseUrl 已含前缀） */
        path: fullPath,
        pathParams: templateParams,
        queryParams,
        querySchemaRef: op["x-olua-query-schema"]?.$ref ?? null,
        queryTypeName: op["x-olua-query-schema"]?.$ref ? refNameOf(op["x-olua-query-schema"].$ref) : synthesizedQueryName,
        synthesizedQueryName,
        bodySchema,
        bodyTypeName: bodySchema?.$ref ? refNameOf(bodySchema.$ref) : null,
        dataSchema: op["x-olua-data-schema"] ?? null,
        dataNullable: op["x-olua-data-nullable"] === true,
        audience: op["x-olua-audience"] ?? "player",
        permissions: op["x-olua-permissions"] ?? [],
        summary: op.summary ?? "",
        description: firstLine(op.description),
        source: `${method.toUpperCase()} ${fullPath}`,
      });
    }
  }

  operations.sort((a, b) => (a.path === b.path ? a.method.localeCompare(b.method) : a.path.localeCompare(b.path)));
  return operations;
}

/** 响应类型表达式（data 的类型） */
function returnTypeOf(op) {
  if (!op.dataSchema) return "null";
  let base = tsType(op.dataSchema, op.doc);
  if (op.dataNullable && !base.includes("null")) base = `${base} | null`;
  return base;
}

