//#region 小工具

function readDoc(file = OPENAPI_FILE) {
  if (!fs.existsSync(file)) {
    throw new Error(`找不到 OpenAPI 文档：${path.relative(ROOT, file)}\n先执行：cd server && npm run swagger:emit`);
  }
  return JSON.parse(fs.readFileSync(file, "utf8"));
}

/** 类型名（去 Dto 后缀 + 别名） */
function typeNameOf(schemaName) {
  return TYPE_ALIASES[schemaName] ?? String(schemaName).replace(/Dto$/, "");
}

/** `#/components/schemas/XxxDto` → `Xxx`（对外类型名） */
function refNameOf(ref) {
  return typeNameOf(String(ref).split("/").pop());
}

const pascal = (text) =>
  String(text)
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");

/** JSDoc 安全化（描述里可能出现 `*\/`） */
const safeDoc = (text) => String(text ?? "").replace(/\*\//g, "*\\/");

/** 多行描述 → JSDoc 行数组（去掉首尾空行） */
function docLines(text) {
  if (!text) return [];
  return safeDoc(text)
    .split(/\r?\n/)
    .map((line) => line.trimEnd())
    .filter((line, index, all) => !(line === "" && (index === 0 || index === all.length - 1)));
}

/** 首段摘要（用于接口方法的 JSDoc） */
function firstLine(text) {
  if (!text) return "";
  return (
    String(text)
      .split(/\r?\n/)
      .map((line) => line.trim())
      .find((line) => line && line !== "---") ?? ""
  );
}

/** 注释缩进对齐（生成物里的 JSDoc） */
function emitDoc(indent, lines) {
  if (!lines.length) return [];
  return [`${indent}/**`, ...lines.map((line) => `${indent} * ${line}`.trimEnd()), `${indent} */`];
}

