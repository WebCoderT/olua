//#region 组装

function buildOutputs(doc = readDoc()) {
  const operations = collectOperations(doc);

  const schemas = new Map();
  for (const [name, schema] of Object.entries(doc.components?.schemas ?? {})) {
    if (SKIP_SCHEMAS.has(name)) continue;
    schemas.set(typeNameOf(name), { schema, doc });
  }

  const extraInterfaces = synthesizeQueryInterfaces(operations);
  const knownNames = new Set([...schemas.keys(), ...extraInterfaces.keys()]);
  const allModelNames = [...knownNames].sort();

  const outputs = new Map();
  for (const target of Object.values(TARGETS)) {
    const own = operations.filter((op) => op.target === target.key);
    // 只 import「本文件签名里直接出现」的类型名：模型之间互相引用由 models 文件自己解决，
    // 多带入的未使用类型会在 `noUnusedLocals` 下报错
    const referenced = new Set();
    for (const op of own) {
      for (const part of [returnTypeOf(op), op.bodyTypeName, op.queryTypeName]) {
        for (const token of tokensOf(part)) if (knownNames.has(token)) referenced.add(token);
      }
    }

    outputs.set(
      path.join(target.dir, target.modelsFile),
      emitModelsFile(target, schemas, extraInterfaces),
    );
    outputs.set(path.join(target.dir, target.routesFile), emitRoutesFile(target, own));
    outputs.set(path.join(target.dir, target.endpointsFile), emitEndpointsFile(target, own, [...referenced].sort(), allModelNames));
  }

  return { operations, outputs };
}

/** 统一的生成物头 */
function header(target, fileName) {
  return [
    "/**",
    ` * ${GENERATED_MARK}`,
    " *",
    ` * 来源：server/openapi.json（由服务端代码生成） → ${target.label}接口文件：${fileName}`,
    " * 重新生成：cd server && npm run gen:api",
    " * 一致性守卫：node tools/audit-api-generated.cjs（生成物落后于文档即 FAIL）",
    " *",
    " * ⚠️ 请勿手改：改接口请改服务端的 DTO / 控制器（含 operationId），再重新生成。",
    " */",
  ];
}

