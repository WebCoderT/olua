#!/usr/bin/env node
/**
 * 接口文件生成器（OpenAPI → 客户端 / 管理端）
 *
 * 输入：`server/openapi.json`（由 `cd server && npm run swagger:emit` 从服务端代码生成）
 * 输出（**生成物，禁止手改**）：
 *
 * | 端 | 文件 | 内容 |
 * |----|------|------|
 * | 客户端 assets/ui/utils/net | `ApiRoutes.ts` | 接口路径表（唯一来源） |
 * |                            | `ApiModels.ts` | 响应 / 入参类型（服务端 DTO 的镜像） |
 * |                            | `Api.ts`       | 接口方法（HealthApi / AuthApi / RoleApi） |
 * | 管理端 admin/src/api      | `routes.ts`    | 接口路径表（唯一来源） |
 * |                            | `models.ts`    | 类型（服务端 DTO 的镜像） |
 * |                            | `endpoints.ts` | 接口方法（authApi / accountsApi / adminsApi / rolesApi） |
 *
 * 为什么必须生成而不是手写：三端本来就是「服务端改一个字段、另外两端忘了改」最容易出事的地方。
 * 现在路径、方法名、类型全部从同一份文档产出，服务端改完重新生成，两端立刻拿到新签名 ——
 * 类型对不上就编译不过，而不是等线上出现一个 undefined。
 *
 * 生成器读的机器可读约定（都由服务端的装饰器写进文档）：
 * - `operationId` 形如 `<模块>.<方法>`（如 `role.save`）→ 决定生成到哪个模块的哪个方法；
 * - `x-olua-audience`（public / player / admin）→ 决定是否带令牌（public 走 `auth: false`）；
 * - `x-olua-data-schema` → 响应里 `data` 的类型（缺省 = data 恒为 null）；
 * - `x-olua-data-nullable` → data 是否可能为 null；
 * - `x-olua-query-schema` → query 参数对应的 DTO（据此生成命名的查询类型）；
 * - `x-olua-permissions` → 写进生成物的注释，让人在两端也能看到「这接口要什么权限」。
 *
 * 用法：
 *   node tools/gen-api.cjs            # 生成（写入磁盘）
 *   node tools/gen-api.cjs --check    # 只比对，不写盘（不一致则退出码 1，守卫脚本用）
 *   node tools/gen-api.cjs --json     # 输出 JSON 摘要
 */

