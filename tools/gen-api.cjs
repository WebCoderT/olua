//#region schema → TS 类型

function resolveRef(ref, doc) {
  const name = String(ref).replace("#/components/schemas/", "");
  const schema = doc.components?.schemas?.[name];
  if (!schema) throw new Error(`悬空 $ref：${ref}（文档里没有这个 schema）`);
  return schema;
}

/** 合并 allOf（Nest 一般已把继承拍平，这里兜底：把各段的 properties / required 并起来） */
function mergeAllOf(parts, doc) {
  const merged = { type: "object", properties: {}, required: [], additionalProperties: undefined };
  const absorb = (schema) => {
    if (!schema) return;
    if (schema.$ref) return absorb(resolveRef(schema.$ref, doc));
    if (schema.allOf) return schema.allOf.forEach(absorb);
    Object.assign(merged.properties, schema.properties ?? {});
    if (Array.isArray(schema.required)) merged.required.push(...schema.required);
    if (schema.additionalProperties !== undefined) merged.additionalProperties = schema.additionalProperties;
  };
  parts.forEach(absorb);
  return merged;
}

/** 取「一个对象 schema 的最终形态」（解开 allOf / $ref） */
function objectShape(schema, doc) {
  if (!schema) return { properties: {}, required: [] };
  if (schema.$ref) return objectShape(resolveRef(schema.$ref, doc), doc);
  if (schema.allOf) return mergeAllOf(schema.allOf, doc);
  return { properties: schema.properties ?? {}, required: schema.required ?? [] };
}

/** schema → TS 类型表达式 */
function tsType(schema, doc) {
  if (!schema) return "unknown";
  if (schema.$ref) return refNameOf(schema.$ref);

  let base;
  if (schema.allOf) {
    // Nest 对「字段类型是另一个 DTO」（`@ApiProperty({ type: XxxDto })`）会写成
    // `allOf: [{ $ref }]`；这种就该还原成那个类型名，而不是当成匿名对象
    const refs = schema.allOf.filter((part) => part.$ref);
    const inline = schema.allOf.filter((part) => !part.$ref && (part.properties || part.required));
    if (refs.length === 1 && !inline.length) {
      base = refNameOf(refs[0].$ref);
    } else {
      const merged = mergeAllOf(schema.allOf, doc);
      const entries = Object.entries(merged.properties ?? {});
      base = entries.length ? `{ ${entries.map(([key, value]) => `${key}: ${tsType(value, doc)}`).join("; ")} }` : "Record<string, unknown>";
    }
  } else if (Array.isArray(schema.enum) && schema.enum.length) {
    base = schema.enum.map((value) => JSON.stringify(value)).join(" | ");
  } else if (schema.type === "array") {
    const item = tsType(schema.items, doc);
    base = `${item.includes("|") ? `(${item})` : item}[]`;
  } else if (schema.type === "string") {
    base = "string";
  } else if (schema.type === "number" || schema.type === "integer") {
    base = "number";
  } else if (schema.type === "boolean") {
    base = "boolean";
  } else if (schema.additionalProperties === true) {
    base = "Record<string, unknown>";
  } else if (schema.additionalProperties && typeof schema.additionalProperties === "object") {
    base = `Record<string, ${tsType(schema.additionalProperties, doc)}>`;
  } else {
    // 既没 type 也没 $ref（服务端漏了 type 的 nullable 字段）：只能当未知
    base = "unknown";
  }

  if (schema.nullable && base !== "null") {
    base = base.includes("|") && !base.startsWith("(") ? `(${base}) | null` : `${base} | null`;
  }
  return base;
}

/** 分隔符拆词（用于「这段类型表达式里用到了哪些生成类型」） */
const tokensOf = (text) => String(text ?? "").split(/[^A-Za-z0-9_]+/).filter(Boolean);

