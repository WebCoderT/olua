//#region 生成：路径表

/** 路径表达式：无参数 → 字符串；有参数 → 箭头函数 */
function pathExpression(op) {
  if (!op.pathParams.length) return JSON.stringify(op.path);
  const template = op.path.replace(/\{([^}]+)\}/g, (_match, name) => `\${encodeURIComponent(${name})}`);
  const args = op.pathParams.map((name) => `${name}: string`).join(", ");
  return `(${args}) => \`${template}\``;
}

function emitRoutesFile(target, operations) {
  const groups = new Map();
  for (const op of operations) {
    if (!groups.has(op.moduleKey)) groups.set(op.moduleKey, []);
    groups.get(op.moduleKey).push(op);
  }

  const lines = [];
  lines.push(...header(target, target.routesFile));
  lines.push("");
  lines.push(...emitDoc("", target.routesDoc));
  lines.push(`export const ${target.routesConst} = {`);
  for (const [moduleKey, group] of groups) {
    lines.push(`  /** ${moduleKey} 模块（${group.length} 个接口） */`);
    lines.push(`  ${moduleKey}: {`);
    for (const op of group) {
      const doc = [`${op.summary || op.methodName}（${op.source}）`];
      if (op.description && op.description !== op.summary) doc.push("", op.description);
      lines.push(...emitDoc("    ", doc));
      lines.push(`    ${op.methodName}: ${pathExpression(op)},`);
    }
    lines.push("  },");
  }
  lines.push("} as const;");
  lines.push("");
  return lines.join("\n");
}

