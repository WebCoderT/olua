/**
 * 装备外观的显示效果（#700）：以素材第一帧为基准的微调
 *
 * 边框基准 = contain 缩进 56×56 外框、中心对齐物品图标中心；
 * 背景基准 = 铺满物品详情弹窗面板。
 * `x` / `y` 是相对基准中心的偏移（**y 向上**，与引擎同口径）、`scale` 乘在适配结果上。
 * 缺省 `{ x: 0, y: 0, scale: 1 }` 与「没有 effect 字段」完全等价（配置快照里可不带）。
 */
export interface AppearanceEffect {
  /** 水平偏移（像素，右为正） */
  x: number;
  /** 垂直偏移（像素，上为正） */
  y: number;
  /** 尺寸倍率（1 = 客户端默认适配结果） */
  scale: number;
}
