/**
 * 一个账号最多几个角色（默认 6，可用 `ROLE_MAX_PER_ACCOUNT` 覆盖）
 *
 * 为什么是 6：客户端选角界面一排 6 个、排满自动换行（`roleSelectorLayout.roleScroll`），
 * 一屏正好一行 —— 上限对齐「一眼能看完」，不必滚动就知道自己还有没有位置。
 *
 * 为什么进配置而不是写死在 `RolesService` 里：e2e 把它压小才验得到「满了会拒」，
 * 正式服要放宽也不必改代码。**脏值回落默认**（非数字 / 小于 1 都当默认值）：
 * 上限读错不该让「建号」变成「一个也建不了」。
 *
 * 客户端不再留同一份数字（#124 的教训：同一个数写两份必然漂移）：建号被拒时
 * 服务端返回 20018 并带上限，客户端照文案提示即可。
 */
export const ROLE_MAX_PER_ACCOUNT_DEFAULT = 6;
